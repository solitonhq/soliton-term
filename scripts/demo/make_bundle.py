#!/usr/bin/env python3
"""Print a Soliton Term workspace bundle that points at the local demo servers.

    python3 scripts/demo/make_bundle.py --dir /tmp/soliton-demo > demo-bundle.json

The bundle contains the *demo* private key generated by demo_server.py (a throw-away key that
only opens the scripted loopback servers). Paste it into Import workspace.
"""
import argparse
import json
import os

ap = argparse.ArgumentParser()
ap.add_argument("--dir", default="/tmp/soliton-demo")
args = ap.parse_args()
key = open(os.path.join(args.dir, "demo_key")).read()

groups = [
    {"id": "grp-prod", "name": "Production Cluster", "parentId": None},
    {"id": "grp-prod-k8s", "name": "Kubernetes Nodes", "parentId": "grp-prod"},
    {"id": "grp-prod-db", "name": "Database Replicas", "parentId": "grp-prod"},
    {"id": "grp-stage", "name": "Staging & QA", "parentId": None},
    {"id": "grp-dmz", "name": "DMZ / Edge Gateways", "parentId": None},
]
creds = [{"id": "cred-ops", "name": "DevOps Automation User", "username": "ops", "secretType": "ssh_key",
          "secretValue": key, "description": "Demo key for the local demo servers"}]


def host(i, name, port, group, tags, os_):
    return {"id": f"host-{i}", "name": name, "hostname": "127.0.0.1", "port": port, "groupId": group,
            "credentialId": "cred-ops", "tags": tags, "os": os_, "injectAliases": True}


hosts = [
    host(1, "k8s-master-01", 2201, "grp-prod-k8s", ["prod", "k8s", "control-plane"], "kubernetes"),
    host(2, "k8s-worker-gpu-01", 2202, "grp-prod-k8s", ["prod", "k8s", "worker", "gpu"], "linux"),
    host(3, "pg-primary-db01", 2203, "grp-prod-db", ["prod", "database", "postgres"], "ubuntu"),
    host(4, "edge-envoy-gw01", 2204, "grp-dmz", ["dmz", "gateway", "envoy"], "linux"),
    host(5, "stage-app-runner", 2205, "grp-stage", ["staging", "docker"], "ubuntu"),
]
print(json.dumps({"schema": "soliton-term-bundle-v1", "exportedAt": "2026-11-01T00:00:00Z", "groups": groups,
                  "credentials": creds, "hosts": hosts, "snippets": [], "aliases": []}, separators=(",", ":")))
