#!/usr/bin/env python3
"""Regenerate THIRD_PARTY_NOTICES.txt.

Lists every third-party component that ends up in the macOS app (Rust crates that are
compiled in, plus npm production packages) with its license and the full license text.
Identical license texts are printed once and referenced afterwards.

Needs a populated cargo registry and node_modules (run `npm ci` and a `cargo build` first):

    python3 scripts/gen_notices.py
"""
import hashlib
import json
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(ROOT, "THIRD_PARTY_NOTICES.txt")
TARGET = "aarch64-apple-darwin"
LICENSE_FILE = re.compile(r"^(licen[cs]e|copying|notice|unlicense)([-_.].*)?$", re.I)


def run(cmd, cwd=ROOT):
    return subprocess.check_output(cmd, cwd=cwd, text=True)


def rust_components():
    meta = json.loads(run(["cargo", "metadata", "--format-version", "1",
                           "--manifest-path", "src-tauri/Cargo.toml", "--filter-platform", TARGET]))
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    pkgs = {p["id"]: p for p in meta["packages"]}
    root = meta["resolve"]["root"]
    seen, stack = set(), [root]
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            # normal dependencies only: build scripts and dev tools are not shipped
            if any(k["kind"] is None for k in d["dep_kinds"]):
                stack.append(d["pkg"])
    seen.discard(root)
    out = []
    for i in sorted(seen, key=lambda x: (pkgs[x]["name"], pkgs[x]["version"])):
        p = pkgs[i]
        out.append({
            "name": p["name"], "version": p["version"],
            "license": p.get("license") or "see source",
            "url": p.get("repository") or p.get("homepage") or f"https://crates.io/crates/{p['name']}",
            "dir": os.path.dirname(p["manifest_path"]),
        })
    return out


def npm_components():
    tree = json.loads(run(["npm", "ls", "--omit=dev", "--all", "--json", "--long"]))
    found = {}

    def walk(d):
        for name, v in (d.get("dependencies") or {}).items():
            path = v.get("path")
            if path and os.path.isdir(path):
                found[(name, v.get("version"))] = {
                    "name": name, "version": v.get("version"),
                    "license": v.get("license") or "see source",
                    "url": (v.get("homepage") or f"https://www.npmjs.com/package/{name}"),
                    "dir": path,
                }
            walk(v)

    walk(tree)
    return [found[k] for k in sorted(found)]


def license_texts(directory):
    texts = []
    try:
        names = sorted(os.listdir(directory))
    except OSError:
        return texts
    for n in names:
        p = os.path.join(directory, n)
        if os.path.isfile(p) and LICENSE_FILE.match(n):
            try:
                with open(p, encoding="utf-8", errors="replace") as f:
                    texts.append((n, f.read().strip()))
            except OSError:
                pass
    return texts


def norm(t):
    return re.sub(r"\s+", " ", t).strip().lower()


def main():
    sections = [("RUST CRATES", rust_components()), ("NPM PACKAGES", npm_components())]
    printed = {}  # normalized-text hash -> first package that carried it
    lines = [
        "THIRD-PARTY SOFTWARE NOTICES",
        "",
        "Soliton Term includes the open-source software listed below. Each component is licensed by its",
        "authors under the terms shown; none of them is affiliated with or endorses Soliton Term.",
        "(Generated by scripts/gen_notices.py — do not edit by hand.)",
        "",
    ]
    missing = []
    for title, comps in sections:
        lines += ["=" * 78, title, "=" * 78, ""]
        for c in comps:
            lines += [f"--- {c['name']} {c['version']}  [{c['license']}]", f"    {c['url']}", ""]
            texts = license_texts(c["dir"])
            if not texts:
                missing.append(f"{c['name']} {c['version']}")
                lines += ["(no license file shipped with this package; see the URL above)", ""]
                continue
            for fname, text in texts:
                h = hashlib.sha256(norm(text).encode()).hexdigest()
                if h in printed:
                    cr = [l.strip() for l in text.splitlines() if re.search(r"copyright|\(c\)", l, re.I)][:3]
                    lines += cr + [f"({fname}: license text identical to the one printed under {printed[h]})", ""]
                else:
                    printed[h] = f"{c['name']} {c['version']}"
                    lines += [text, ""]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines).rstrip() + "\n")
    total = sum(len(c) for _, c in sections)
    print(f"wrote {OUT}: {total} components, {len(printed)} distinct license texts, {len(lines)} lines")
    if missing:
        print("no license file for:", ", ".join(missing), file=sys.stderr)


if __name__ == "__main__":
    main()
